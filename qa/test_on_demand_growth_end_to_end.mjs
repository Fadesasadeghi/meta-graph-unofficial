import { test } from 'node:test';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import http from 'node:http';
import https from 'node:https';

import { AccountStore } from '../dist/accounts/account_store.js';
import { MockInstagramProvider } from '../dist/providers/mock_instagram_provider.js';
import { InstagramAnalyticsService } from '../dist/analytics/instagram_analytics_service.js';
import { AnalyticsSnapshotStore } from '../dist/analytics/analytics_snapshot_store.js';
import { AnalyticsHistoryService } from '../dist/analytics/analytics_history_service.js';
import { OnDemandGrowthService } from '../dist/advisor/on_demand_growth_service.js';

/**
 * Test-only adapter around MockInstagramProvider that maps local UUIDs from
 * AccountStore to mock provider accounts ('demo-account-1') while preserving
 * the correct account identity in profile and media results.
 */
class TestMockInstagramProviderAdapter {
  constructor(provider, mapping = new Map()) {
    this.provider = provider;
    this.mapping = mapping;
  }

  get source() {
    return this.provider.source;
  }

  mapAccountId(accountId) {
    return this.mapping.get(accountId) ?? accountId;
  }

  async getProfile(accountId) {
    const targetId = this.mapAccountId(accountId);
    const result = await this.provider.getProfile(targetId);
    if (!result.ok) {
      return result;
    }

    // Preserve local account identity in profile data
    return {
      ...result,
      data: {
        ...result.data,
        id: accountId
      }
    };
  }

  async listMedia(accountId, options) {
    const targetId = this.mapAccountId(accountId);
    const result = await this.provider.listMedia(targetId, options);
    if (!result.ok) {
      return result;
    }

    // Preserve local account identity across all media items
    return {
      ...result,
      data: {
        ...result.data,
        items: result.data.items.map(item => ({
          ...item,
          accountId
        }))
      }
    };
  }

  async getMediaInsights(accountId, mediaId) {
    const targetId = this.mapAccountId(accountId);
    return await this.provider.getMediaInsights(targetId, mediaId);
  }

  async listComments(accountId, mediaId, options) {
    const targetId = this.mapAccountId(accountId);
    return await this.provider.listComments(targetId, mediaId, options);
  }
}

test('On-Demand Growth Backend: End-to-End Pipeline Integration', async () => {
  // 1. Network trap: verify zero outbound HTTP/HTTPS/fetch network calls
  let networkCalls = 0;
  const originalFetch = globalThis.fetch;
  const originalHttpRequest = http.request;
  const originalHttpsRequest = https.request;

  globalThis.fetch = async (...args) => {
    networkCalls++;
    throw new Error(`Live network request forbidden in offline test: fetch(${JSON.stringify(args[0])})`);
  };

  http.request = (...args) => {
    networkCalls++;
    throw new Error('Live HTTP request forbidden in offline test.');
  };

  https.request = (...args) => {
    networkCalls++;
    throw new Error('Live HTTPS request forbidden in offline test.');
  };

  const root = await mkdtemp(join(tmpdir(), 'hermes-growth-e2e-'));

  try {
    const accountsDir = join(root, 'accounts');
    const snapshotsDir = join(root, 'snapshots');

    // 2. Setup AccountStore with standard UUID generation (no custom id)
    const accountStore = new AccountStore(accountsDir);

    const ownerA = 'owner-alice';
    const ownerB = 'owner-bob';

    // Register account using standard UUID-based AccountStore API
    const accountA = await accountStore.create({
      ownerId: ownerA,
      username: 'demo.creator',
      accountType: 'creator'
    });

    // Verify UUID format generated by AccountStore
    assert.match(accountA.id, /^[0-9a-f-]{36}$/i);
    assert.equal(accountA.ownerId, ownerA);
    assert.equal(accountA.username, 'demo.creator');

    // 3. Instantiate pipeline components with actual MockInstagramProvider and adapter
    const actualMockProvider = new MockInstagramProvider();
    const accountMapping = new Map([
      [accountA.id, 'demo-account-1']
    ]);
    const adaptedProvider = new TestMockInstagramProviderAdapter(
      actualMockProvider,
      accountMapping
    );

    const analyticsService = new InstagramAnalyticsService(adaptedProvider);
    const snapshotStore = new AnalyticsSnapshotStore(accountStore, snapshotsDir);
    const historyService = new AnalyticsHistoryService(analyticsService, snapshotStore);
    const growthService = new OnDemandGrowthService(historyService);

    // 4. FIRST REQUEST: Explicit user-triggered analysis (baseline snapshot, no trend)
    const firstResult = await growthService.analyze(ownerA, accountA.id);

    assert.equal(firstResult.ok, true, 'First analysis must succeed.');
    assert.equal(firstResult.source, 'mock');
    assert.ok(firstResult.fetchedAt);

    // Verify analytics report in first request preserves local UUID identity
    const firstAnalytics = firstResult.data.analytics;
    assert.equal(firstAnalytics.report.accountId, accountA.id);
    assert.equal(firstAnalytics.report.username, 'demo.creator');
    assert.equal(firstAnalytics.report.source, 'mock');
    assert.equal(firstAnalytics.report.followersCount, 12500);
    assert.equal(firstAnalytics.report.analyzedPostCount, 3);
    assert.equal(firstAnalytics.report.averageEngagementRatePct, 8.23);
    assert.equal(firstAnalytics.report.engagementRateDenominator, 'followers');
    assert.deepEqual(firstAnalytics.report.contentMix, {
      reel: 1,
      image: 1,
      carousel: 1,
      video: 0
    });

    // Verify ranked posts preserve account identity
    assert.ok(
      firstAnalytics.report.rankedPosts.length > 0
    );

    // Verify snapshot was created
    assert.ok(firstAnalytics.snapshot);
    assert.equal(firstAnalytics.snapshot.ownerId, ownerA);
    assert.equal(firstAnalytics.snapshot.accountId, accountA.id);
    assert.equal(firstAnalytics.snapshot.source, 'mock');

    // Verify first request produces NO trend
    assert.equal(firstAnalytics.trend, null, 'First request must have no trend.');
    assert.ok(
      firstAnalytics.warnings.some(w =>
        w.includes('No previous snapshot exists')
      ),
      'Must contain warning about missing previous snapshot.'
    );

    // Verify growth recommendations (advice)
    const firstAdvice = firstResult.data.advice;
    assert.equal(firstAdvice.accountId, accountA.id);
    assert.equal(firstAdvice.source, 'mock');
    assert.ok(firstAdvice.experiments.length > 0, 'Advice must contain experiments.');

    // Verify prioritized decisions
    const firstDecisions = firstResult.data.decisions;
    assert.equal(firstDecisions.accountId, accountA.id);
    assert.equal(firstDecisions.source, 'mock');
    assert.ok(firstDecisions.decisions.length > 0, 'Must produce actionable decisions.');
    assert.ok(
      firstDecisions.decisions.every(d => d.requiresApproval === true),
      'All decisions must require explicit human approval.'
    );
    assert.ok(
      firstDecisions.warnings.some(w =>
        w.includes('No historical trend available')
      ),
      'Decisions must warn about lack of historical trend on baseline run.'
    );

    // Verify disk persistence of first snapshot
    const savedSnapshotsAfterFirst = await snapshotStore.list(ownerA, accountA.id);
    assert.equal(savedSnapshotsAfterFirst.length, 1);
    assert.equal(savedSnapshotsAfterFirst[0].id, firstAnalytics.snapshot.id);

    // 5. SECOND REQUEST: Subsequent analysis after a time interval produces historical comparison
    await new Promise(resolve => setTimeout(resolve, 50));

    const secondResult = await growthService.analyze(ownerA, accountA.id);

    assert.equal(secondResult.ok, true, 'Second analysis must succeed.');
    assert.equal(secondResult.source, 'mock');

    const secondAnalytics = secondResult.data.analytics;
    assert.notEqual(
      secondAnalytics.snapshot.id,
      firstAnalytics.snapshot.id,
      'Second snapshot must have a unique ID.'
    );

    // Verify that the second request produces a historical trend comparison
    assert.notEqual(secondAnalytics.trend, null, 'Second request must produce a trend comparison.');
    const trend = secondAnalytics.trend;
    assert.equal(trend.accountId, accountA.id);
    assert.equal(trend.source, 'mock');
    assert.equal(trend.previousSnapshotId, firstAnalytics.snapshot.id);
    assert.equal(trend.currentSnapshotId, secondAnalytics.snapshot.id);
    assert.ok(Date.parse(trend.previousDate) < Date.parse(trend.currentDate));

    // Verify metric changes in historical comparison
    assert.ok(trend.followers !== null, 'Follower trend must be computed.');
    assert.equal(trend.followers.previous, 12500);
    assert.equal(trend.followers.current, 12500);
    assert.equal(trend.followers.absoluteChange, 0);
    assert.equal(trend.followers.direction, 'unchanged');

    assert.ok(trend.engagementRate !== null, 'Engagement rate trend must be computed.');
    assert.equal(trend.engagementRate.previous, 8.23);
    assert.equal(trend.engagementRate.current, 8.23);
    assert.equal(trend.engagementRate.absoluteChange, 0);
    assert.equal(trend.engagementRate.direction, 'unchanged');

    assert.equal(trend.dataQuality.completeMediaHistory, true);
    assert.equal(trend.dataQuality.previousCompletePosts, 2);
    assert.equal(trend.dataQuality.currentCompletePosts, 2);

    // Verify second request decisions reflect the presence of trend data
    const secondDecisions = secondResult.data.decisions;
    assert.ok(secondDecisions.decisions.length > 0);
    assert.ok(
      secondDecisions.decisions.every(d => d.requiresApproval === true),
      'All decisions on second run must require approval.'
    );
    // On the second run, 'No historical trend available for comparison' should NOT be present
    assert.ok(
      !secondDecisions.warnings.some(w =>
        w.includes('No historical trend available for comparison')
      ),
      'Historical trend available warning should be absent on second run.'
    );

    // Verify 2 snapshots now persist for ownerA
    const savedSnapshotsAfterSecond = await snapshotStore.list(ownerA, accountA.id);
    assert.equal(savedSnapshotsAfterSecond.length, 2);

    // 6. CROSS-OWNER ISOLATION
    // ownerB cannot analyze ownerA's account
    await assert.rejects(
      growthService.analyze(ownerB, accountA.id),
      /Account not found for this owner/,
      'Owner B must not be permitted to analyze Owner A accounts.'
    );

    // ownerB cannot access ownerA's snapshots
    await assert.rejects(
      snapshotStore.list(ownerB, accountA.id),
      /Account not found for this owner/,
      'Owner B must not be permitted to list Owner A snapshots.'
    );

    // Register a distinct account for ownerB
    const accountB = await accountStore.create({
      ownerId: ownerB,
      username: 'bob.creator',
      accountType: 'creator'
    });
    assert.equal(accountB.ownerId, ownerB);
    assert.notEqual(accountB.id, accountA.id);
    assert.match(accountB.id, /^[0-9a-f-]{36}$/i);

    // ownerB analyzing an account not mapped in adapter fails safely with NOT_FOUND from MockInstagramProvider
    const unmappedResult = await growthService.analyze(ownerB, accountB.id);
    assert.equal(unmappedResult.ok, false);
    assert.equal(unmappedResult.source, 'mock');
    assert.equal(unmappedResult.error.code, 'NOT_FOUND');
    assert.equal('data' in unmappedResult, false);

    // Snapshots for ownerB remain empty
    const ownerBSnapshots = await snapshotStore.list(ownerB, accountB.id);
    assert.equal(ownerBSnapshots.length, 0);

    // ownerA's snapshots remain unaffected (still 2)
    const ownerASnapshotsFinal = await snapshotStore.list(ownerA, accountA.id);
    assert.equal(ownerASnapshotsFinal.length, 2);

    // 7. VERIFY ZERO NETWORK CALLS
    assert.equal(networkCalls, 0, 'No live Instagram or external HTTP/HTTPS calls may occur.');

    console.log('PASS: Full on-demand growth pipeline end-to-end integration verified.');
    console.log('PASS: Baseline snapshot created without trend.');
    console.log('PASS: Second snapshot generated historical trend comparison.');
    console.log('PASS: Cross-owner isolation verified.');
    console.log('PASS: Zero live Instagram network calls verified.');
  } finally {
    // Restore network globals
    globalThis.fetch = originalFetch;
    http.request = originalHttpRequest;
    https.request = originalHttpsRequest;

    await rm(root, { recursive: true, force: true });
  }
});
